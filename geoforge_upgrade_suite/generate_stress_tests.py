#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate thousands of reproducible executable property-regression tests.

Test vectors exercise mathematically distinct integer coordinate instances.
These are generated TEST LINES, not additional DDAR2 production algorithms.
The generator is committed so new versions can reproduce the test matrix.
"""
from __future__ import annotations
from pathlib import Path
import random

ROOT=Path(__file__).resolve().parent
FAMILIES=(
    'lines','inversion','radical','polynomial','projective','coordinates',
    'circles','convex','language','ratio','tokenizer','affine',
)

HEADER='''# Automatically generated by generate_stress_tests.py — DO NOT HAND EDIT.
# Deterministic, distinct integer-coordinate property tests.
from pathlib import Path
import sys
from fractions import Fraction as Q
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from geometry_exact import (Vec2, Line, Circle, Inversion, radical_center, HPoint,
    Mat3, Polynomial, midpoint, cross_ratio, convex_hull, point_inside_convex_polygon,
    polygon_area2, is_convex_polygon, squared_distance)
from symbolic_coordinates import (NumericalEquationValidator, CoordinateNormalization,
    SystemSolvabilityGuard)
from formal_language import NaturalLanguageGeometryParser
from neural_baseline import GeometryTokenizer
from dataset_engineering import deterministic_seed, stable_hash, FamilySplit, DatasetConfig

'''


def generate_family(family,count=220,seed=123456):
    if family not in FAMILIES:raise ValueError('unrecognized family')
    rng=random.Random(seed+len(family)*31)
    snippets=[HEADER]
    for i in range(count):
        x=rng.randrange(-1000,1000)
        y=rng.randrange(-1000,1000)
        u=rng.randrange(1,60)
        v=rng.randrange(1,60)
        w=rng.randrange(1,60)
        t=rng.randrange(1,60)
        # All parameters are concrete deterministic cases. Each function
        # invokes several distinct mathematical assertions.
        prefix=f'def test_stress_matrix_{family}_{i:04d}():\n'
        if family=='lines':
            lines=[
                f'    a = Vec2({x}, {y}); b = Vec2({x+u}, {y+v})',
                f'    p = Vec2({x+w}, {y-t})',
                '    line = Line.through(a, b)',
                '    foot = line.projection(p)',
                '    assert line.contains(a) and line.contains(b) and line.contains(foot)',
                '    assert (p-foot).dot(b-a) == 0',
                '    assert line.reflect(line.reflect(p)) == p',
            ]
        elif family=='inversion':
            lines=[
                f'    center = Vec2({x}, {y})',
                f'    p = Vec2({x+u}, {y+v})',
                f'    transform = Inversion(center, {w*w})',
                '    q = transform.point(p)',
                '    assert q != center and transform.point(q) == p',
                f'    assert (p-center).dot(q-center) == {w*w}',
                '    assert squared_distance(p,center)*squared_distance(q,center) == transform.radius2**2',
            ]
        elif family=='radical':
            lines=[
                f'    a = Circle(Vec2({x}, {y}), {u*u})',
                f'    b = Circle(Vec2({x+v}, {y}), {w*w})',
                f'    c = Circle(Vec2({x}, {y+t}), {(u+v)*(u+v)})',
                '    center = radical_center(a,b,c)',
                '    assert a.power(center) == b.power(center)',
                '    assert b.power(center) == c.power(center)',
                '    assert a.radical_axis(b).contains(center)',
            ]
        elif family=='polynomial':
            lines=[
                '    x = Polynomial.variable(2, 0)',
                '    y = Polynomial.variable(2, 1)',
                f'    expression = (x-y)*(x+y+{u})',
                '    q, remainder = expression.divided_remainder((x-y,))',
                f'    assert not remainder and q[0] == x+y+{u}',
                f'    assert expression.eval(({v}, {w})) == ({v}-{w})*({v}+{w}+{u})',
                f'    assert expression.derivative(0).eval(({v}, {w})) == 2*{v}+{u}',
            ]
        elif family=='projective':
            lines=[
                f'    p = HPoint({x}, {y}, 1)',
                f'    m = Mat3((({u},0,{v}),(0,{w},-{t}),(0,0,1)))',
                '    inverse = m.invert()',
                '    q = m.point(p)',
                '    assert inverse.point(q).normalized() == p.normalized()',
                '    line = p.cross(HPoint(p.x+1,p.y+3,1))',
                '    assert line.contains(p) and line.contains(HPoint(p.x+1,p.y+3,1))',
            ]
        elif family=='coordinates':
            lines=[
                f'    a = ({x}, {y}); b = ({x+2*u}, {y+2*v})',
                f'    m = ({x+u}, {y+v})',
                '    points = {"a":a,"b":b,"m":m}',
                '    assert NumericalEquationValidator.check("midp",("m","a","b"),points)',
                '    assert NumericalEquationValidator.check("coll",("a","m","b"),points)',
                '    assert SystemSolvabilityGuard(points).verify_condition("distinct a b")',
            ]
        elif family=='circles':
            lines=[
                f'    center = Vec2({x}, {y})',
                f'    a = center+Vec2({u},0); b=center+Vec2(0,{u})',
                f'    c = center+Vec2(-{u},0); d=center+Vec2(0,-{u})',
                '    circle = Circle.through(a,b,c)',
                f'    assert circle.center == center and circle.radius2 == {u*u}',
                '    assert circle.contains(d) and circle.contains(a)',
            ]
        elif family=='convex':
            lines=[
                f'    a=Vec2({x},{y}); b=Vec2({x+u},{y})',
                f'    c=Vec2({x+u},{y+v}); d=Vec2({x},{y+v})',
                '    shape=(a,b,c,d)',
                '    hull=convex_hull((b,d,a,c,a,d))',
                '    assert len(hull)==4 and is_convex_polygon(shape)',
                '    assert abs(polygon_area2(shape)) == 2*(b.x-a.x)*(d.y-a.y)',
                '    assert point_inside_convex_polygon(midpoint(a,c),shape,strict=True)',
            ]
        elif family=='language':
            alphabet='ABCDEFGHIJKLMNOPQRSTUVWXYZ'
            names=[alphabet[(i*5+j)%26] for j in range(6)]
            if len(set(names))!=6:raise RuntimeError('bad generated uppercase point names')
            a,b,c,d,e,f=names
            lines=[
                f'    text = "{a}{b} e paralelo a {c}{d}; Demonstre que {e}{f} e perpendicular a {a}{b}."',
                '    parsed = NaturalLanguageGeometryParser().parse(text)',
                f'    assert parsed.hypotheses == ("para {a} {b} {c} {d}",)',
                f'    assert parsed.goal == "perp {e} {f} {a} {b}"',
                '    assert parsed.is_complete() and len(parsed.evidence) == 2',
            ]
        elif family=='ratio':
            lines=[
                f'    a = Vec2({x},{y}); b=Vec2({x+4*u},{y})',
                f'    c = Vec2({x+u},{y}); d=Vec2({x+3*u},{y})',
                '    value=cross_ratio(a,b,c,d)',
                '    assert value == Q(1,9)',
                f'    shift=Vec2({v},{w})',
                '    assert cross_ratio(a+shift,b+shift,c+shift,d+shift) == value',
                '    assert cross_ratio(a*3,b*3,c*3,d*3)==value',
            ]
        elif family=='tokenizer':
            lines=[
                f'    source="midp pt{i} a{i} b{i}; para x{i} y{i} a{i} b{i}"',
                '    tok=GeometryTokenizer.fit((source,))',
                '    tokens=tok.encode(source)',
                '    reconstructed=tok.decode(tokens)',
                '    assert reconstructed==" ".join(tok.tokens(source))',
                '    assert tok.encode(source)==tokens',
                '    assert tok.vocab[0]=="<pad>" and tok.vocab[1]=="<bos>"',
            ]
        elif family=='affine':
            lines=[
                f'    points={{"a":({x},{y}),"b":({x+u},{y+v})}}',
                f'    shift=({w},{t})',
                '    shifted=CoordinateNormalization.translate(None,points,shift)',
                '    recovered=CoordinateNormalization.translate(None,shifted,(-shift[0],-shift[1]))',
                '    assert recovered==points',
                '    rotated=CoordinateNormalization.rotate90(points)',
                '    assert CoordinateNormalization.rotate90(CoordinateNormalization.rotate90(CoordinateNormalization.rotate90(rotated)))==points',
            ]
        else:raise RuntimeError(family)
        snippets.append(prefix+'\n'.join(lines)+'\n\n')
    output=ROOT/'tests'/f'test_stress_{family}.py'
    output.write_text(''.join(snippets),encoding='utf-8')
    return output


def main():
    count=220
    files=[generate_family(name,count=count) for name in FAMILIES]
    print('Generated',len(files),'test files and',len(files)*count,'executable tests')
    print('lines',sum(len(p.read_text().splitlines()) for p in files))


if __name__=='__main__':main()
